func main() {
	cfg := config.Load()

	db := database.NewPostgres(cfg)
	defer db.Close()

	rdb := database.NewRedis(cfg)
	defer rdb.Close()

	seeder.Run(db)

	srv := server.New(cfg, db, rdb)
	log.Printf("Bapok Service running on port %s", cfg.Port)
	log.Fatal(srv.Start())
}
